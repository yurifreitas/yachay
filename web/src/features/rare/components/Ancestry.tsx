/** The viewer's resolved theme, watched. Three states, only two of which stamp an
 *  attribute, so both the stamp and the OS setting have to be observed. */
function useThemeMode(): "light" | "dark" {
  const [mode, setMode] = useState<"light" | "dark">(() =>
    typeof document === "undefined" ? "light" : resolveMode()
  );
  useEffect(() => {
    const sync = () => setMode(resolveMode());
    const mo = new MutationObserver(sync);
    mo.observe(document.documentElement, { attributes: true, attributeFilter: ["data-theme"] });
    const mq = window.matchMedia("(prefers-color-scheme: dark)");
    mq.addEventListener("change", sync);
    return () => { mo.disconnect(); mq.removeEventListener("change", sync); };
  }, []);
  return mode;
}

function Tile({
  label, value, note, tone,
}: { label: string; value: string; note: string; tone?: "over" | "under" | "warn" }) {
  return (
    <div className={css.tile}>
      <span className={css.tileLabel}>{label}</span>
      <span className={`${css.tileValue} ${tone ? css[tone] : ""}`}>{value}</span>
      <span className={css.tileNote}>{note}</span>
    </div>
  );
}

